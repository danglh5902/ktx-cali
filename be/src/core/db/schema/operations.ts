export const maintenanceTickets = pgTable("maintenance_tickets", {
  id: id(),
  orgId: uuid("org_id").notNull(),
  branchId: uuid("branch_id").notNull().references(() => branches.id),
  buildingId: uuid("building_id").references(() => buildings.id),
  floorId: uuid("floor_id").references(() => floors.id),
  roomId: uuid("room_id").references(() => rooms.id),
  bedId: uuid("bed_id").references(() => beds.id),
  assetId: uuid("asset_id").references((): AnyPgColumn => assets.id),
  ticketNo: text("ticket_no").notNull(),
  category: text("category").notNull(),
  title: text("title").notNull(),
  description: text("description"),
  attachments: text("attachments").array(),
  priority: text("priority").notNull().default("NORMAL"),
  slaResponseDeadline: timestamp("sla_response_deadline", { withTimezone: true }),
  slaResolveDeadline: timestamp("sla_resolve_deadline", { withTimezone: true }),
  slaBreached: boolean("sla_breached").notNull().default(false),
  slaBreachedAt: timestamp("sla_breached_at", { withTimezone: true }),
  pausedDurationMinutes: integer("paused_duration_minutes").notNull().default(0),
  reportedBy: uuid("reported_by"),
  reporterType: text("reporter_type"),
  reportedAt: timestamp("reported_at", { withTimezone: true }).notNull().defaultNow(),
  assignedTo: uuid("assigned_to"),
  assignedBy: uuid("assigned_by"),
  assignedAt: timestamp("assigned_at", { withTimezone: true }),
  startedAt: timestamp("started_at", { withTimezone: true }),
  resolvedAt: timestamp("resolved_at", { withTimezone: true }),
  closedAt: timestamp("closed_at", { withTimezone: true }),
  resolution: text("resolution"),
  resolutionAttachments: text("resolution_attachments").array(),
  laborCost: money("labor_cost"),
  partsCost: money("parts_cost"),
  totalCost: money("total_cost"),
  chargeToTenant: boolean("charge_to_tenant").notNull().default(false),
  chargedInvoiceId: uuid("charged_invoice_id").references(() => invoices.id),
  expenseId: uuid("expense_id").references(() => expenses.id),
  status: text("status").notNull().default("OPEN"),
  mergedIntoTicketId: uuid("merged_into_ticket_id"),
  tenantRating: integer("tenant_rating"),
  tenantFeedback: text("tenant_feedback"),
}, (t) => ({
  ticketNoUnique: uniqueIndex("maintenance_tickets_ticket_no_key").on(t.ticketNo),
}));

