import { sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  boolean,
  date,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { branches, buildings, floors, rooms, beds } from "./org-permissions.js";
import { customers } from "./tenancy.js";
import { expenses, invoices } from "./finance.js";
